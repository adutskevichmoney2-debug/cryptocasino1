-- ── place_bet, with server-side pricing ─────────────────────────────────────

create or replace function public.place_bet(
  p_selections jsonb,
  p_stake      numeric,
  p_coin       coin,
  p_type       text
)
returns public.bets
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_odds numeric(12,4);
  v_bet public.bets;
  v_selection jsonb;
  v_priced jsonb := '[]'::jsonb;
  v_outcome_id text;
  v_real_odds numeric(12,4);
  v_count int;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  perform public.assert_active_account(v_user);

  if p_selections is null or jsonb_array_length(p_selections) = 0 then
    raise exception 'empty_slip' using errcode = 'P0001';
  end if;
  if p_stake is null or p_stake <= 0 then
    raise exception 'invalid_stake' using errcode = 'P0001';
  end if;
  if p_type not in ('single','combo') then
    raise exception 'invalid_bet_type' using errcode = 'P0001';
  end if;

  v_count := jsonb_array_length(p_selections);
  if v_count > 20 then
    raise exception 'too_many_selections' using errcode = 'P0001';
  end if;

  -- Price every selection from the catalogue. The odds field the client sent is
  -- discarded; the stored selection carries the price actually used.
  v_odds := 1;
  for v_selection in select * from jsonb_array_elements(p_selections) loop
    v_outcome_id := v_selection ->> 'outcomeId';

    select odds into v_real_odds
    from public.sport_outcomes
    where outcome_id = v_outcome_id;

    if v_real_odds is null then
      raise exception 'unknown_outcome' using errcode = 'P0001';
    end if;

    v_odds := v_odds * v_real_odds;
    v_priced := v_priced || jsonb_build_array(jsonb_set(v_selection, '{odds}', to_jsonb(v_real_odds)));
  end loop;

  -- A single bet carries one selection; a slip of singles is placed one call
  -- per bet, so only the first price applies here.
  if p_type = 'single' then
    v_odds := (v_priced -> 0 ->> 'odds')::numeric;
  end if;
  v_odds := round(v_odds, 4);

  perform public.apply_ledger(
    p_user_id => v_user,
    p_coin    => p_coin,
    p_delta   => -p_stake,
    p_type    => 'bet',
    p_note    => v_priced -> 0 ->> 'eventLabel'
  );

  insert into public.bets (user_id, bet_type, selections, stake, coin, total_odds, potential_win)
  values (v_user, p_type, v_priced, p_stake, p_coin, v_odds, round(p_stake * v_odds, 18))
  returning * into v_bet;

  update public.profiles
  set xp = xp + floor(p_stake)::bigint,
      wagered_total = wagered_total + p_stake
  where id = v_user;

  return v_bet;
end;
$$;

grant execute on function public.place_bet(jsonb, numeric, coin, text) to authenticated;