-- ============================================================================
-- Authoritative odds catalogue
-- ============================================================================
-- place_bet previously read each selection's odds straight out of the client
-- JSON and only recomputed the product, so a crafted request could claim any
-- price it liked and settle_bet would pay it. Odds now live in the database and
-- the client's numbers are ignored entirely.
--
-- Values mirror the deterministic generation in src/services/shared/sports.ts
-- (seeded PRNG keyed by outcome id), so what the player sees is what settles.
-- Regenerate this table whenever the event fixtures change.
-- ----------------------------------------------------------------------------

create table if not exists public.sport_outcomes (
  outcome_id text primary key,
  event_id   text not null,
  odds       numeric(12,4) not null check (odds >= 1),
  updated_at timestamptz not null default now()
);

create index if not exists sport_outcomes_event_idx on public.sport_outcomes(event_id);

alter table public.sport_outcomes enable row level security;

-- The catalogue is public reference data; writes are service-role only.
drop policy if exists sport_outcomes_select on public.sport_outcomes;
create policy sport_outcomes_select on public.sport_outcomes for select using (true);

